//! Standard finite-field Diffie–Hellman moduli with generator 2.

use super::gex::GexSizes;

const fn digit(value: u8) -> u8 {
    match value {
        b'0'..=b'9' => value - b'0',
        b'A'..=b'F' => value - b'A' + 10,
        _ => panic!("invalid MODP prime encoding"),
    }
}

const fn decode<const N: usize>(encoded: &str) -> [u8; N] {
    let text = encoded.as_bytes();
    assert!(text.len() == N * 2);
    let mut prime = [0; N];
    let mut index = 0;
    while index < N {
        prime[index] = (digit(text[index * 2]) << 4) | digit(text[index * 2 + 1]);
        index += 1;
    }
    prime
}

