/// Choose a default GEX modulus from groups 14 and 16 within the request
/// bounds: the smallest one that reaches the preferred size, or the largest
/// available when none does (RFC 4419 section 3).
pub fn default_gex_prime(parameters: GexSizes) -> Option<&'static [u8]> {
    let sizes = parameters.sizes();
    let group_bits = |prime: &&[u8]| (prime.len() * 8) as u32;
    // Ordered by size, so the first match is the smallest and the last
    // eligible group is the largest.
    let mut eligible = [GROUP14, GROUP16]
        .into_iter()
        .filter(|prime| sizes.contains(&group_bits(prime)));
    eligible
        .clone()
        .find(|prime| group_bits(prime) >= parameters.preferred())
        .or_else(|| eligible.next_back())
}

